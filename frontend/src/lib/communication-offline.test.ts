import 'fake-indexeddb/auto';
import assert from 'node:assert/strict';
import { beforeEach, after, test } from 'node:test';
import { db } from './db';
import { configureOffline, syncAll } from './offline-engine';
import { cancelRejectedMessageChange, localRead, localWrite, rememberRead } from './local-api';
const account='11111111-1111-4111-8111-111111111111', conversation='22222222-2222-4222-8222-222222222222';
let online=false;
Object.defineProperty(globalThis,'navigator',{configurable:true,value:{get onLine(){return online;}}});
Object.defineProperty(globalThis,'window',{configurable:true,value:new EventTarget()});
const identity={id:account,fullName:'Student',role:'STUDENT'};
Object.defineProperty(globalThis,'localStorage',{configurable:true,value:{getItem:()=>JSON.stringify(identity)}});
beforeEach(async()=>{online=false;for(const table of db.tables)await table.clear();configureOffline(async()=>{throw new Error('offline')},()=>account);});
after(()=>db.close());
test('messages persist across database reopening, require a known writable conversation and survive lost acknowledgements',async()=>{
 await assert.rejects(localWrite('post',`/chat/conversations/${conversation}/messages`,{body:'Hello'}));
 await rememberRead(`/chat/conversations/${conversation}`,{}, {id:conversation,canPost:true});
 const message=await localWrite('post',`/chat/conversations/${conversation}/messages`,{body:'Hello'});
 assert.equal(message.synced,0);assert.equal(await db.queue.count(),1);
 db.close();await db.open();
 assert.equal((await localRead(`/chat/conversations/${conversation}/messages`,{})).data[0].body,'Hello');
 online=true;const receipts=new Map();let sends=0;let lose=true;
 configureOffline(async(_method,_path,payload)=>{const outcomes=[];for(const op of payload.operations){if(!receipts.has(op.opId)){sends++;receipts.set(op.opId,{opId:op.opId,status:'applied',data:{id:op.entityId,body:op.data.body,conversationId:conversation}});}outcomes.push(receipts.get(op.opId));}if(lose){lose=false;throw new Error('response lost');}return {outcomes};},()=>account);
 await assert.rejects(syncAll());assert.equal(await db.queue.count(),1);
 await syncAll();assert.equal(sends,1);assert.equal(await db.queue.count(),0);
 assert.equal((await localRead(`/chat/conversations/${conversation}/messages`,{})).data[0].synced,1);
 configureOffline(async()=>{throw new Error('offline')},()=> 'another-account');
 assert.equal((await localRead(`/chat/conversations/${conversation}/messages`,{})).data.length,0);
});
test('local posts, comments and replies preserve parent references when server IDs change',async()=>{
 const post=await localWrite('post','/community/posts',{body:'Post'});
 const comment=await localWrite('post',`/community/posts/${post.id}/comments`,{body:'Comment'});
 await localWrite('post',`/community/comments/${comment.id}/replies`,{body:'Reply'});
 const feed=await localRead('/community/feed',{});assert.equal(feed[0].comments.length,2);
 const canonicalPost='33333333-3333-4333-8333-333333333333',canonicalComment='44444444-4444-4444-8444-444444444444';
 online=true;configureOffline(async(_method,_path,payload)=>({outcomes:payload.operations.map((op:any)=>({opId:op.opId,status:'applied',data:{id:op.entityId===post.id?canonicalPost:op.entityId===comment.id?canonicalComment:op.entityId}}))}),()=>account);
 await syncAll();const comments=await db.table('communityComments').toArray();
 assert(comments.every(row=>row.postId===canonicalPost));assert.equal(comments.find(row=>row.body==='Reply').parentId,canonicalComment);
 assert.equal(await db.queue.count(),0);
});
test('school posts remain restricted and nickname changes stay pending without changing another account',async()=>{
 await assert.rejects(localWrite('post','/community/posts',{body:'School',schoolPost:true}));
 const nickname=await localWrite('patch','/community/nickname',{nickname:'  أبو عمر  '});
 assert.equal(nickname.id,account);assert.equal(nickname.nickname,'أبو عمر');assert.equal(nickname.synced,0);
 assert.equal((await db.queue.toArray())[0].table,'accountPreferences');
});

test('sent message edits and deletions persist their server baseline and reject another author', async () => {
 const messageId='33333333-3333-4333-8333-333333333333';
 await rememberRead(`/chat/conversations/${conversation}`,{}, {id:conversation,canPost:true,isAdmin:false});
 await rememberRead(`/chat/conversations/${conversation}/messages`,{}, {data:[{id:messageId,conversationId:conversation,body:'Original',senderId:account,editedAt:null}]});
 const edit=await localWrite('patch',`/chat/conversations/${conversation}/messages/${messageId}`,{body:'Edited'});
 assert.equal(edit.synced,0); assert.equal(edit.body,'Edited');
 const op=(await db.queue.toArray())[0]; assert.equal(op.data.previousBody,'Original'); assert.equal(op.data.previousEditedAt,null);
 db.close();await db.open();assert.equal((await localRead(`/chat/conversations/${conversation}/messages`,{})).data[0].body,'Edited');
 await assert.rejects(localWrite('delete',`/chat/conversations/${conversation}/messages/${messageId}`,undefined));
 await db.queue.clear();await db.table('chatMessages').update([account,messageId],{synced:1,senderId:'another'});
 await assert.rejects(localWrite('patch',`/chat/conversations/${conversation}/messages/${messageId}`,{body:'Unauthorized'}));
 await assert.rejects(localWrite('delete',`/chat/conversations/${conversation}/messages/${messageId}`,undefined));
 await db.table('chatMessages').update([account,messageId],{senderId:account});
 const removed=await localWrite('delete',`/chat/conversations/${conversation}/messages/${messageId}`,undefined);
 assert.equal(removed.synced,0);assert.equal(removed.pendingDelete,1);
 assert.equal((await localRead(`/chat/conversations/${conversation}/messages`,{})).data.length,0);
 assert.equal((await db.queue.toArray())[0].action,'delete');
 const deletion=(await db.queue.toArray())[0];
 await assert.rejects(cancelRejectedMessageChange(messageId));
 await db.queue.update(deletion.id!,{error:'تغيّرت الرسالة من جهاز آخر'});
 const rejected=(await localRead(`/chat/conversations/${conversation}/messages`,{})).data[0];
 assert.equal(rejected.rejectedChange,true);assert.equal(rejected.syncError,'تغيّرت الرسالة من جهاز آخر');
 await cancelRejectedMessageChange(messageId);
 assert.equal(await db.queue.count(),0);
 assert.equal((await db.table('chatMessages').get([account,messageId])).pendingDelete,0);
});
